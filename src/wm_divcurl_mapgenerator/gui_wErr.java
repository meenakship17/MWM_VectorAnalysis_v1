    private void getReciprocal(ImageProcessor ip) {
        float[] pixels = (float[]) ip.getPixels();
        for (int i = 0; i < ip.getWidth() * ip.getHeight(); i++) {
            if (pixels[i] == 0f) {
                pixels[i] = Float.NaN;
            } else {
                pixels[i] = 1f / pixels[i];
            }
        }
        ip.resetMinAndMax();
    }

