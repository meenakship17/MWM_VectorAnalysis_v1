    private Roi getSampledPixelsROI(ImagePlus impRes) {
        impRes.setProcessor(impRes.getProcessor().convertToByteProcessor());
        impRes.getProcessor().setThreshold(1, 255, 3);       //255 is max for 8-bit image 
        ThresholdToSelection tts = new ThresholdToSelection();
        Roi thresholdedROI = tts.convert(impRes.getProcessor());
        return thresholdedROI;
    }

