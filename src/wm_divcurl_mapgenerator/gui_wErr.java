    private ImagePlus thresholdValues(ImagePlus image, double minValue, double maxValue, boolean withNaN) {
        image = image.duplicate();
        ImageProcessor IP = image.getProcessor();
        IP.resetRoi();
        ThresholdToSelection tts = new ThresholdToSelection();
        IP.setThreshold(minValue, maxValue, 3);
        Roi thresholdROI = tts.convert(IP);
        if (withNaN) {
            IP.setValue(Double.NaN);
        } else {
            IP.setValue(0d);
        }

        IP.fillOutside(thresholdROI);
        ImagePlus result = new ImagePlus(image.getTitle(), IP);
        return result;
    }

